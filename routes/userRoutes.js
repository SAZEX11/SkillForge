const express = require('express');
const { requireAuth } = require('../middleware/auth');
const { requireRole } = require('../middleware/role');
const user = require('../controllers/userController');
const router = express.Router();
router.use(requireAuth, requireRole('user'));
router.get('/dashboard', user.dashboard);
router.get('/skill-analysis', user.skillAnalysis);
router.get('/progress', user.progress);
router.get('/achievements', user.achievements);
router.get('/notifications', user.notifications);
router.post('/notifications/read-all', user.readAll);
router.post('/notifications/:id/read', user.markRead);
router.get('/profile', user.profile);
router.post('/profile', user.updateProfile);
router.get('/settings', user.settings);
router.post('/settings', user.updateSettings);
router.post('/settings/password', user.changePassword);
module.exports = router;
