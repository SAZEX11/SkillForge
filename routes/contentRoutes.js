const express = require('express');
const { requireAuth } = require('../middleware/auth');
const { requireRole } = require('../middleware/role');
const c = require('../controllers/contentController');
const router = express.Router();
// Server-side gate: only content managers (and admins, who hold this role too).
router.use('/content', requireAuth, requireRole('content_manager', 'admin'));
router.get('/content', c.dashboard);
router.get('/content/skills', c.skills);
router.post('/content/skills', c.saveSkill);
router.post('/content/skills/:id', c.saveSkill);
router.get('/content/questions', c.questions);
router.get('/content/questions/new', c.newQuestion);
router.post('/content/questions', c.saveQuestion);
router.get('/content/questions/:id/edit', c.editQuestion);
router.post('/content/questions/:id', c.saveQuestion);
router.post('/content/questions/:id/status', c.toggleQuestion);
router.get('/content/assessments', c.assessments);
router.get('/content/assessments/new', c.newAssessment);
router.post('/content/assessments', c.saveAssessment);
router.get('/content/assessments/:id/edit', c.editAssessment);
router.post('/content/assessments/:id', c.saveAssessment);
router.post('/content/assessments/:id/status', c.setAssessmentStatus);
router.post('/content/assessments/:id/questions', c.assessmentQuestion);
router.post('/content/assessments/:id/questions/:qid/:action', c.assessmentQuestion);
router.get('/content/resources', c.resources);
router.get('/content/resources/new', c.newResource);
router.post('/content/resources', c.saveResource);
router.get('/content/resources/:id/edit', c.editResource);
router.post('/content/resources/:id', c.saveResource);
router.post('/content/resources/:id/status', c.toggleResource);
module.exports = router;
